const { test } = require('node:test');
const assert = require('node:assert/strict');
require('./mock-catalog-storage.cjs');
const express = require('express');
const cookieParser = require('cookie-parser');
const mongoose = require('mongoose');
const Admin = require('../models/admin.model');
const Genre = require('../models/genre.model');

test('catalog list contract, search, status, pagination and multipart editing', async t => {
  process.env.TOKEN_SECRET = 'catalog-test-secret';
  const database = `technosara_catalog_test_${process.pid}_${Date.now()}`;
  await mongoose.connect('mongodb://127.0.0.1:27017', { dbName: database, serverSelectionTimeoutMS: 3000 });
  t.after(async () => {
    assert.equal(mongoose.connection.name, database);
    await mongoose.connection.dropDatabase();
    await mongoose.disconnect();
  });
  const admin = await Admin.create({ name: 'Catalog admin', email: 'catalog@example.com', password: 'password-123', role: 'superAdmin' });
  const app = express();
  app.use(express.json(), cookieParser());
  app.use('/api', require('../routes/admin.route'));
  app.use(require('../middleware/error.middleware'));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  let cookie;
  const request = async (path, method = 'GET', body, headers = {}) => {
    const response = await fetch(base + path, {
      method, headers: { 'content-type': 'application/json', ...(cookie ? { cookie } : {}), ...headers },
      ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
    });
    return { status: response.status, body: await response.json(), headers: response.headers };
  };
  assert.equal((await request('/genres')).status, 401);
  const login = await request('/account/login', 'POST', { email: admin.email, password: 'password-123' });
  cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/genres', 'POST', { name: 'Denied', slug: 'denied' }, { origin: 'https://untrusted.example' })).status, 403);
  for (let index = 0; index < 6; index++) {
    const created = await request('/genres', 'POST', { name: `Genre ${index}`, slug: `genre-${index}`, is_active: index % 2 === 0 });
    assert.equal(created.status, 201);
    assert.deepEqual(Object.keys(created.body).sort(), ['acknowledgement', 'description', 'message']);
  }
  const list = await request('/genres');
  assert.deepEqual(Object.keys(list.body).sort(), ['acknowledgement', 'data', 'description', 'message', 'total']);
  assert.equal(list.body.data.length, 5);
  assert.equal(list.body.total, 6);
  assert.equal(list.body.data[0].creator._id, String(admin._id));
  assert.equal((await request('/genres?page=2&limit=5')).body.data.length, 1);
  assert.equal((await request('/genres?page=invalid&limit=invalid')).body.data.length, 5);
  assert.equal((await request('/genres?search=Genre%205')).body.total, 1);
  assert.equal((await request('/genres?search=^Genre')).body.total, 6);
  assert.equal((await request('/genres?status=active')).body.total, 3);
  assert.equal((await request('/genres?status=inactive')).body.total, 3);
  const original = (await request('/genres?limit=100')).body.data.map(item => item._id);
  assert.equal((await request('/genres/reorder', 'PATCH', { id: 'invalid', targetId: original[0] })).status, 400);
  assert.equal((await request('/genres/reorder', 'PATCH', { id: original[0], targetId: original[0] })).status, 400);
  assert.equal((await request('/genres/reorder', 'PATCH', { id: '000000000000000000000000', targetId: original[0] })).status, 404);
  assert.equal((await request('/genres/reorder', 'PATCH', { id: original[5], targetId: original[0] })).status, 200);
  const reordered = [original[5], ...original.slice(0, 5)];
  assert.deepEqual((await request('/genres?limit=100')).body.data.map(item => item._id), reordered);
  assert.deepEqual((await request('/genres/all')).body.data.map(item => item._id), reordered);
  assert.deepEqual((await request('/genres?page=2&limit=5')).body.data.map(item => item._id), reordered.slice(5));
  assert.equal((await request('/genres/reorder', 'PATCH', { id: original[5], targetId: original[4] })).status, 200);
  assert.deepEqual((await request('/genres?limit=100')).body.data.map(item => item._id), original);
  const genre = await Genre.findOne({ slug: 'genre-0' });
  const body = new FormData();
  body.append('name', JSON.stringify('ویرایش ژانر'));
  const updated = await fetch(`${base}/genres/${genre._id}`, { method: 'PATCH', headers: { cookie }, body });
  assert.equal(updated.status, 200);
  assert.equal((await updated.json()).acknowledgement, true);
  assert.equal((await request(`/genres/${genre._id}`)).body.data.name, 'ویرایش ژانر');
  assert.equal((await Genre.findById(genre._id)).slug, 'genre-0');
  assert.equal((await Genre.findById(genre._id)).sort_order, 0);
  assert.equal((await request(`/genres/${genre._id}`, 'DELETE')).status, 200);
  assert.equal((await request('/genres')).body.total, 5);
  assert.equal((await Genre.collection.findOne({ _id: genre._id })).isDeleted, true);
  assert.equal((await request(`/genres/${genre._id}`, 'DELETE')).status, 404);
  assert.ok((await request('/companies/countries')).body.data.some(country => country.code === 'IR'));
  const companyBody = { name: 'Sample Company', type: 'publisher', country_code: 'IR', logo: 'data:image/png;base64,' + (await require('sharp')({ create: { width: 120, height: 80, channels: 3, background: '#8899aa' } }).png().toBuffer()).toString('base64') };
  assert.equal((await request('/companies', 'POST', companyBody)).status, 201);
  assert.equal((await request('/companies', 'POST', companyBody)).status, 201);
  const companies = (await request('/companies')).body.data;
  assert.equal(companies.length, 2);
  assert.notEqual(companies[0].slug, companies[1].slug);
  assert.match(companies[0].logo, /^https:\/\/arvan.example.com\/company\//);
  assert.match(companies[0].preview_url, /preview-64.webp$/);
  assert.equal(companies[0].status, 'active');
  assert.equal((await request(`/companies/${companies[0]._id}`, 'PATCH', { name: 'Renamed Company', english_name: 'Renamed Company', slug: 'renamed-company', country_code: 'JP' })).status, 200);
  const editedCompany = (await request(`/companies/${companies[0]._id}`)).body.data;
  assert.equal(editedCompany.slug, 'renamed-company');
  assert.equal(editedCompany.name, 'Renamed Company');
  assert.equal(Object.hasOwn(editedCompany, 'english_name'), false);
  assert.equal(editedCompany.status, 'active');
  assert.equal(editedCompany.country_code, 'JP');
  const genreImage = 'data:image/png;base64,' + (await require('sharp')({ create: { width: 120, height: 80, channels: 3, background: '#8899aa' } }).png().toBuffer()).toString('base64');
  const translatedGenre = { name_en: 'Action adventure', name: 'اکشن ماجراجویی', slug: 'action-adventure', image: genreImage, description: 'توضیحات ژانر', is_active: true };
  assert.equal((await request('/genres', 'POST', translatedGenre)).status, 201);
  const savedGenre = (await request('/genres?search=' + encodeURIComponent('ماجراجویی'))).body.data[0];
  for (const [key, value] of Object.entries(translatedGenre)) if (key !== 'image') assert.equal(savedGenre[key], value);
  assert.match(savedGenre.image, /^https:\/\/arvan.example.com\/genre\//);
  assert.equal((await request('/genres', 'POST', { ...translatedGenre, slug: 'action-adventure-2' })).status, 201);
  assert.equal((await request(`/genres/${savedGenre._id}`, 'PATCH', { description: 'ویرایش' })).status, 200);
  assert.equal((await request(`/genres/${savedGenre._id}`)).body.data.image, savedGenre.image);
  assert.equal((await request(`/genres/${savedGenre._id}`, 'PATCH', { image: 'data:text/html;base64,abcd' })).status, 400);
  assert.equal((await request(`/genres/${savedGenre._id}`, 'PATCH', { image: '' })).status, 200);
  assert.equal((await request(`/genres/${savedGenre._id}`)).body.data.image, '');
  admin.status = 'inactive';
  await admin.save();
  assert.equal((await request('/genres')).status, 401);
});
