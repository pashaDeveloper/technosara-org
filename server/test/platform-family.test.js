const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const express = require('express');
const cookieParser = require('cookie-parser');
const Admin = require('../models/admin.model');
const Family = require('../models/platformFamily.model');
const Platform = require('../models/platform.model');

test('platform families: authentication, search, pagination, platform hierarchy and company references', async t => {
  process.env.TOKEN_SECRET = 'isolated-platform-family-test';
  const database = `technosara_family_test_${process.pid}_${Date.now()}`;
  await mongoose.connect('mongodb://127.0.0.1:27017', { dbName: database, serverSelectionTimeoutMS: 3000 });
  t.after(async () => { assert.equal(mongoose.connection.name, database); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  await Family.init();
  const admin = await Admin.create({ name: 'Admin', email: 'family@example.com', password: 'password-123', role: 'superAdmin' });
  const app = express();
  app.use(express.json(), cookieParser());
  app.use('/api', require('../routes/admin.route'));
  app.use(require('../middleware/error.middleware'));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  let cookie;
  async function request(path, method = 'GET', body) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, {
      method, headers: { 'content-type': 'application/json', ...(cookie ? { cookie } : {}) },
      ...(body ? { body: JSON.stringify(body) } : {})
    });
    return { status: response.status, body: await response.json(), headers: response.headers };
  }
  assert.equal((await request('/platform-families')).status, 401);
  const login = await request('/account/login', 'POST', { email: admin.email, password: 'password-123' });
  cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/platform-families', 'POST', { name: ' ' })).status, 400);
  const created = await request('/platform-families', 'POST', { name: 'PlayStation' });
  assert.equal(created.status, 201);
  const familyId = created.body.data._id;
  assert.equal((await request('/platform-families', 'POST', { name: 'playstation' })).status, 409);
  await Family.insertMany(Array.from({ length: 24 }, (_, i) => ({ name: `Family ${String(i).padStart(2, '0')}`, key: `family-${i}` })));
  const first = (await request('/platform-families?limit=20')).body;
  const second = (await request('/platform-families?limit=20&page=2')).body;
  assert.equal(first.data.length, 20); assert.equal(first.hasMore, true);
  assert.equal(second.data.length, 5); assert.equal(second.hasMore, false);
  assert.equal(new Set([...first.data, ...second.data].map(item => item._id)).size, 25);
  assert.equal((await request('/platform-families?search=STATION')).body.total, 1);
  assert.equal((await request('/platform-families?search=%5B')).body.total, 0);
  assert.equal((await request(`/platform-families/${familyId}`)).body.data.name, 'PlayStation');
  const Company = require('../models/company.model');
  const company = await Company.create({ name: 'Sony', slug: 'sony', type: 'publisher' });
  assert.equal((await request('/platforms', 'POST', { name: 'Invalid', manufacturer_id: 'bad' })).status, 400);
  assert.equal((await request('/platforms', 'POST', { name: 'Invalid', parent_id: String(new mongoose.Types.ObjectId()) })).status, 400);
  assert.equal((await request('/platforms', 'POST', { name: 'PlayStation', manufacturer_id: String(company._id), short_name: 'ignored', family_id: familyId })).status, 201);
  const parent = await Platform.findOne({ name: 'PlayStation' });
  assert.equal(parent.short_name, undefined);
  assert.equal(parent.family_id, undefined);
  assert.equal(String(parent.manufacturer_id), String(company._id));
  assert.equal((await request('/platforms', 'POST', { name: 'PS5', english_name: 'PlayStation 5', slug: 'playstation-5', parent_id: String(parent._id), manufacturer_id: String(company._id) })).status, 201);
  const child = await Platform.findOne({ name: 'PS5' });
  assert.equal(child.english_name, 'PlayStation 5');
  assert.equal(child.slug, 'playstation-5');
  assert.equal(String(child.parent_id), String(parent._id));
  assert.equal((await request('/platforms/' + parent._id, 'PATCH', { parent_id: String(child._id) })).status, 400);
  assert.equal((await request('/platforms/' + child._id, 'PATCH', { parent_id: String(child._id) })).status, 400);
  assert.equal((await request('/platforms/' + child._id, 'PATCH', { manufacturer_id: String(new mongoose.Types.ObjectId()) })).status, 400);
  assert.equal((await request('/platforms/' + child._id, 'PATCH', { name: 'PS5 Pro', english_name: 'PlayStation 5 Pro', slug: 'playstation-5-pro' })).status, 200);
  assert.equal(String((await Platform.findById(child._id)).parent_id), String(parent._id));
  assert.equal((await Platform.findById(child._id)).slug, 'playstation-5-pro');
  const list = (await request('/platforms')).body.data;
  const listedChild = list.find(item => item._id === String(child._id));
  assert.equal(listedChild.parent_id.name, 'PlayStation');
  assert.equal(listedChild.manufacturer_id.name, 'Sony');
  const options = (await request('/platforms/all')).body.data;
  assert.equal(options.find(item => item._id === String(child._id)).parent_id, String(parent._id));
  assert.equal((await request('/platforms/' + child._id, 'PATCH', { parent_id: null, manufacturer_id: null })).status, 200);
  const cleared = await Platform.findById(child._id);
  assert.equal(cleared.parent_id, null);
  assert.equal(cleared.manufacturer_id, null);
  const parentId = String(parent._id);
  const childId = String(child._id);
  const reorder = body => request('/platforms/reorder', 'PATCH', body);
  assert.equal((await reorder({ id: parentId, targetId: parentId, position: 'before' })).status, 400);
  assert.equal((await reorder({ id: 'invalid', targetId: childId, position: 'after' })).status, 400);
  assert.equal((await reorder({ id: parentId, targetId: childId, position: 'invalid' })).status, 400);
  assert.equal((await reorder({ id: parentId, targetId: String(new mongoose.Types.ObjectId()), position: 'before' })).status, 404);
  assert.equal((await reorder({ id: parentId, targetId: childId, position: 'before' })).status, 200);
  assert.deepEqual((await request('/platforms')).body.data.map(item => item._id), [parentId, childId]);
  assert.equal((await reorder({ id: parentId, targetId: childId, position: 'after' })).status, 200);
  assert.deepEqual((await request('/platforms')).body.data.map(item => item._id), [childId, parentId]);
  assert.equal((await request('/platforms?limit=1&page=2')).body.data[0]._id, parentId);
  assert.deepEqual((await request('/platforms/all')).body.data.map(item => item._id), [childId, parentId]);
  assert.equal((await request('/platforms/' + childId, 'PATCH', { name: 'Renamed' })).status, 200);
  assert.deepEqual((await request('/platforms')).body.data.map(item => item._id), [childId, parentId]);
  const previousCookie = cookie;
  cookie = undefined;
  assert.equal((await reorder({ id: parentId, targetId: childId, position: 'before' })).status, 401);
  cookie = previousCookie;
});
