const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const Collection = require('../models/collection.model');
const Game = require('../models/game.model');
for (const name of ['admin', 'company', 'media', 'genre']) require('../models/' + name + '.model');
const service = require('../services/collection.service');
const games = require('../services/game.service');
test('collections persist shared games, validate membership, filter, reorder and soft delete', async t => {
  const database = 'technosara_collection_test_' + process.pid + '_' + Date.now();
  await mongoose.connect('mongodb://127.0.0.1:27017', { dbName: database, serverSelectionTimeoutMS: 3000 });
  t.after(async () => { assert.equal(mongoose.connection.name, database); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  await Collection.init();
  const creator = new mongoose.Types.ObjectId();
  const call = async (fn, req = {}) => {
    let result; let status = 200;
    await fn({ body: {}, query: {}, params: {}, admin: { _id: creator }, ...req }, { status(code) { status = code; return this; }, json(body) { result = body; } });
    return { status, ...result };
  };
  const records = await Game.create([{ title: 'One', slug: 'one', status: 'released' }, { title: 'Two', slug: 'two', status: 'released' }]);
  const ids = records.map(game => String(game._id));
  assert.equal((await call(service.addCollection, { body: { name: 'Hidden gems', slug: 'hidden-gems', game_ids: ids } })).status, 201);
  assert.equal((await call(service.addCollection, { body: { name: 'Favorites', slug: 'favorites', game_ids: JSON.stringify([ids[0], ids[0]]) } })).status, 201);
  const first = await Collection.findOne({ slug: 'hidden-gems' });
  const second = await Collection.findOne({ slug: 'favorites' });
  assert.equal(second.game_ids.length, 1);
  assert.equal((await call(games.getGames, { query: { collection_id: String(first._id) } })).total, 2);
  assert.equal((await call(games.getGames, { query: { collection_id: 'bad' } })).status, 400);
  await call(service.updateCollection, { params: { id: first._id }, body: { description: 'Updated' } });
  assert.equal((await Collection.findById(first._id)).game_ids.length, 2);
  await assert.rejects(call(service.updateCollection, { params: { id: first._id }, body: { game_ids: [String(new mongoose.Types.ObjectId())] } }), { status: 400 });
  assert.equal((await call(service.addCollection, { body: { name: 'Bad', slug: 'bad', game_ids: ['bad'] } })).status, 400);
  await call(service.updateCollection, { params: { id: first._id }, body: { game_ids: [], is_active: false } });
  assert.equal((await Collection.findById(first._id)).game_ids.length, 0);
  assert.equal((await call(service.getCollections, { query: { status: 'inactive' } })).total, 1);
  await call(service.reorderCollection, { body: { id: String(second._id), targetId: String(first._id) } });
  assert.equal(String((await call(service.getCollections)).data[0]._id), String(second._id));
  await call(service.deleteCollection, { params: { id: second._id } });
  assert.equal((await call(games.getGames, { query: { collection_id: String(second._id) } })).total, 0);
  assert.equal(await Game.countDocuments(), 2);
  assert.equal((await call(service.getCollections)).total, 1);
});
